def candidates(w):
    out = []
    if len(w) > 2 and w.endswith("e") and not w.endswith(("ee","oe")):
        out.append(w[:-1])
    if w.endswith("es") and len(w) > 3:
        out.append(w[:-2] + "s")
    if w.endswith("ies") and len(w) > 3:
        out.append(w[:-3] + "ys")
    if w.endswith("ie"):
        out.append(w[:-2] + "y")
    if w.endswith("lie"):
        out.append(w[:-3] + "ly")
    if len(w) > 2 and w[-1] == w[-2] and w[-1] in "bcdfglmnprst":
        out.append(w[:-1])
    if w.endswith("nes"):
        out.append(w + "s")
    if w.endswith("les"):
        out.append(w + "s")
    if w.endswith("ick"):
        out.append(w[:-1])
    if w.endswith("eth") and len(w) > 4:
        stem = w[:-3]
        out.append(stem + ("es" if stem.endswith(("s","x","z","sh","ch")) else "s"))
    if w.endswith("est") and len(w) > 4:
        out.append(w[:-3]); out.append(w[:-2])
    if w.startswith("v"):
        out.append("u" + w[1:])
    if w.startswith("vv"):
        out.append("w" + w[2:])
    for i,ch in enumerate(w):
        if ch == "u" and i > 0:
            out.append(w[:i] + "v" + w[i+1:])
    for i,ch in enumerate(w):
        if ch == "v" and i > 0:
            out.append(w[:i] + "u" + w[i+1:])
    for i in range(len(w)-1):
        if w[i] == w[i+1] and w[i] in "bcdfghjklmnpqrstvwxyz":
            out.append(w[:i] + w[i+1:])
    if "ck" in w:
        out.append(w.replace("ck", "c", 1))
    if w.endswith("ely"):
        out.append(w[:-3] + "ly")
    if w.endswith("esse"):
        out.append(w[:-1])
    if w.endswith("our"):
        out.append(w[:-3] + "or")
    if w.endswith("re") and len(w) > 3 and w[-3] not in "aeiou":
        out.append(w[:-2] + "er")
    if w.endswith("ise"):
        out.append(w[:-3] + "ize")
    if w.endswith("ising"):
        out.append(w[:-5] + "izing")
    if w.endswith("yse"):
        out.append(w[:-3] + "yze")
    if w.endswith("que"):
        out.append(w[:-3])
    if w.endswith("ques"):
        out.append(w[:-4])
        out.append(w[:-4] + "cs")
    for i,ch in enumerate(w):
        if ch == "y" and 0 < i:
            out.append(w[:i] + "i" + w[i+1:])
    if "oo" in w:
        out.append(w.replace("oo","o",1))
    if "ee" in w:
        out.append(w.replace("ee","e",1))
    if w.startswith("i") and len(w) > 1 and w[1] not in "aeiou":
        out.append("j" + w[1:])
    if w.startswith("quh"):
        out.append("wh" + w[3:])
    if "æ" in w or "œ" in w:
        out.append(w.replace("æ","ae").replace("œ","oe"))
        out.append(w.replace("æ","e").replace("œ","e"))
    return out

def modernize_word(w):
    lw = w.lower().strip("'")
    if lw in D:
        return D[lw]
    if is_modern(lw):
        return None  # keep as-is
    # try single transforms, then chains (up to 3 rounds)
    frontier = [w.lower()]
    seen = set(frontier)
    for _ in range(3):
        nxt = []
        for cand_src in frontier:
            for c in candidates(cand_src):
                if c in seen or not c:
                    continue
                seen.add(c)
                if acceptable(c):
                    return c
                nxt.append(c)
        frontier = nxt
    return "?"  # unresolved

def restore_case(orig, new):
    if new == "?":
        return orig
    if orig.isupper():
        return new.upper()
    if orig[:1].isupper():
        return new.capitalize()
    return new

